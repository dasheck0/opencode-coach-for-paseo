import { afterEach, expect, it, vi } from 'vitest';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { createElement } from 'react';
vi.mock('react-native', () => ({ View: 'View', Text: 'Text', Pressable: 'Pressable' }));
import { SessionHeatmap } from '../client/session-heatmap';
import { I18nProvider } from '../client/i18n';
import type { Surface } from '../client/ui';
const mounted: ReactTestRenderer[] = [];
afterEach(async () => { await act(async () => { mounted.splice(0).forEach(r => r.unmount()); }); });
it.each([[false, 'en'], [true, 'de']] as const)('shows a small localized cell popover for hover/focus/touch, including empty cells (%s,%s)', async (compact, language) => {
  (globalThis as Record<string, unknown>).IS_REACT_ACT_ENVIRONMENT = true;
  const surface = { theme: { colors: { foreground: '#eee', foregroundMuted: '#aaa', surface0: '#111', surface1: '#222', border: '#444', accent: '#080' } }, layout: { compact } } as Surface;
  const hours = Array(168).fill(0); hours[1 * 24 + 8] = 7;
  let r!: ReactTestRenderer;
  await act(async () => { r = create(createElement(I18nProvider, { language, children: createElement(SessionHeatmap, { ...surface, hours }) })); }); mounted.push(r);
  const cells = () => r.root.findAllByType('Pressable' as never);
  const details = () => r.root.findAllByProps({ accessibilityLabel: language === 'de' ? 'Zellendetails' : 'Cell details' });
  expect(cells()).toHaveLength(168); expect(details()).toHaveLength(0);
  await act(async () => cells()[32].props.onHoverIn());
  expect(details()).toHaveLength(1); expect(JSON.stringify(r.toJSON())).toContain(language === 'de' ? 'Montag' : 'Monday');
  expect(details()[0].findAllByType('Text' as never).map(n => n.props.children)).toEqual([language === 'de' ? 'Montag' : 'Monday', '08:00–09:00 UTC', '7 Sessions']);
  await act(async () => cells()[32].props.onHoverOut()); expect(details()).toHaveLength(0);
  await act(async () => cells()[167].props.onFocus());
  expect(details()[0].findAllByType('Text' as never).map(n => n.props.children)).toContain('0 Sessions');
  expect(details()[0].findAllByType('Text' as never).map(n => n.props.children)).toContain('23:00–24:00 UTC');
  await act(async () => cells()[167].props.onBlur()); expect(details()).toHaveLength(0);
  await act(async () => cells()[32].props.onPress());
  await act(async () => cells()[32].props.onHoverOut()); expect(details()).toHaveLength(1);
  await act(async () => cells()[32].props.onPress()); expect(details()).toHaveLength(0);
});
