import { workspaceTimelines } from '../shared/session-groups';
import { afterEach, expect, it, vi } from 'vitest';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { createElement } from 'react';
vi.mock('react-native', () => ({ View: 'View', Text: 'Text', Pressable: 'Pressable' }));
vi.mock('@getpaseo/plugin/client/ui', () => ({ SettingsSelect: 'SettingsSelect' }));
import { SessionTimeline } from '../client/session-timeline';
import { timelineLayout, timelineTicks } from '../client/session-timeline-model';
import { I18nProvider } from '../client/i18n';
import type { SessionSummary } from '../shared/model';
import type { Surface } from '../client/ui';
const start = Date.parse('2026-11-08T23:00:00Z'), end = Date.parse('2026-11-10T01:00:00Z');
const session = (id: string, a = start, b = end): SessionSummary => ({ id, adapterId: 'f', sourceId: 's', title: `Session ${id}`, projectName: 'Fixture project', workspaceName: 'Named worktree', directory: '/fixture', created: a, updated: b, parentId: null, inputTokens: null, outputTokens: null, cost: null });
const mounted: ReactTestRenderer[] = [];
afterEach(async () => { await act(async () => { mounted.splice(0).forEach(r => r.unmount()); }); });
it('keeps a continuous multi-day span, clips to bounds and includes exact endpoint markers', () => {
  const result = timelineLayout([session('long', start - 3600000, end + 3600000), session('short', start + 3600000, start + 7200000)], start, end);
  expect(result.segments[0]).toMatchObject({ left: 0, width: 1 });
  expect(result.segments[1].left).toBeCloseTo(1 / 26);
  expect(result.segments[1].width).toBeCloseTo(1 / 26);
  const ticks = timelineTicks(result.start, result.end, 5);
  expect(ticks[0]).toBe(start); expect(ticks.at(-1)).toBe(end);
  expect(new Set(ticks.map(t => new Date(t).toISOString().slice(0, 10))).size).toBe(3);
});
it('keeps overlaps on a single track while keeping every session selectable and handles zero-length/empty input', () => {
  const result = timelineLayout(Array.from({ length: 50 }, (_, i) => session(String(i))), start, end);
  expect(result.lanes).toBe(1); expect(result.crowded).toBe(true); expect(result.segments).toHaveLength(50);
  expect(timelineLayout([session('point', start, start)]).end).toBeGreaterThan(start);
  expect(timelineLayout([], start, end).segments).toEqual([]);
});
it.each([[false, 'en'], [true, 'de']] as const)('inspects inline on hover/focus/click and opens analysis only explicitly (%s,%s)', async (compact, language) => {
  (globalThis as Record<string, unknown>).IS_REACT_ACT_ENVIRONMENT = true;
  const surface = { theme: { colors: { foreground: '#111', foregroundMuted: '#555', surface2: '#eee', surface1: '#fff', border: '#ccc', accent: '#080' } }, layout: { compact } } as Surface;
  const onOpenSession = vi.fn(); let r!: ReactTestRenderer;
  await act(async () => { r = create(createElement(I18nProvider, { language, children: createElement(SessionTimeline, { ...surface, sessions: [session('one'), session('two', start + 1, end)], onOpenSession }) })); }); mounted.push(r);
  const button = () => r.root.findByProps({ accessibilityLabel: language === 'de' ? 'Session ansehen: Session two' : 'Inspect session: Session two' });
  const selector = () => r.root.findByType('SettingsSelect' as never);
  await act(async () => button().props.onHoverIn());
  expect(selector().props.value).toBe('two'); expect(onOpenSession).not.toHaveBeenCalled();
  expect(JSON.stringify(r.toJSON())).toContain('Named worktree');
  await act(async () => button().props.onHoverOut()); expect(selector().props.value).toBe('one');
  await act(async () => button().props.onFocus()); expect(selector().props.value).toBe('two');
  await act(async () => button().props.onBlur());
  await act(async () => button().props.onPress()); await act(async () => button().props.onHoverOut());
  expect(selector().props.value).toBe('two'); expect(onOpenSession).not.toHaveBeenCalled();
  await act(async () => r.root.findByProps({ accessibilityLabel: language === 'de' ? 'Auswerten: Session two' : 'Analyze Session two' }).props.onPress());
  expect(onOpenSession).toHaveBeenCalledExactlyOnceWith('two');
  await act(async () => selector().props.onValueChange('one')); expect(selector().props.value).toBe('one');
  expect(r.root.findAllByType('Text' as never).every(n => n.props.style.color)).toBe(true);
});

it('groups by workspace identity within a project while retaining sessions and separating matching workspace names', () => {
  const a = { ...session('a'), projectId: 'p', workspaceId: 'w1' };
  const b = { ...session('b'), projectId: 'p', workspaceId: 'w1', directory: '/fixture/subdir' };
  const c = { ...session('c'), projectId: 'p', workspaceId: 'w2' };
  const d = { ...session('d'), projectId: 'q', workspaceId: 'w1' };
  const groups = workspaceTimelines([a, b, c, d]);
  expect(groups.map(g => g.sessions.map(s => s.id))).toEqual([['a', 'b'], ['c'], ['d']]);
  for (const group of groups) expect(timelineLayout(group.sessions).lanes).toBe(1);
});
